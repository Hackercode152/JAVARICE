public class IfAndIfElse {
    public static void main(String[] args) {

        int score = 95;

        // if statement
        if (score >= 90) {
            System.out.println("PASIKAT!");
        }

        // if-else statement
        if (score >= 75) {
            System.out.println("MAGALING!");
        } else {
            System.out.println("UWI KANA.");
        }

    }
}